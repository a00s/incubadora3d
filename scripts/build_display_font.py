#!/usr/bin/env python3
"""Subset Ucglib fonts without changing any glyph pixels/metrics."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
fontdir = Path.home() / 'Arduino/libraries/Ucglib/src/clib'
labels = 'CO SENSOR FAIL TEMP TOO HOT LOST BLOQUEADO R RECUPERANDO INT PORTA ABERTA CO2 PAUSADO'
specs = [
    ('ucg_pixel_font_data.c','ucg_font_7x13_mr','incubadora_font_7x13',
     set(' +-./*0123456789chikmnp'+labels)),
    ('ucg_vector_font_data.c','ucg_font_inr16_mn','incubadora_font_inr16',set('-0123456789')),
]
lines = ['#pragma once', '// Generated by scripts/build_display_font.py.',
         '// Misc-Fixed: public domain. Inconsolata LGC: SIL OFL 1.1.',
         '// See DISPLAY_FONT_OFL.txt. Original glyph bytes/metrics preserved.']
for filename, original, name, keep in specs:
    source = (fontdir/filename).read_text(encoding='latin1')
    match = re.search(original+r'\[\d+\].*?= \{(.*?)\};',source,re.S)
    attribution = source[source.rfind('/*', 0, match.start()):source.index('*/', source.rfind('/*', 0, match.start()))+2]
    lines.append(attribution)
    data = list(map(int,re.findall(r'\d+',match.group(1))))
    glyphs = []
    pos = 21
    while data[pos+1]:
        size = data[pos+1]
        if chr(data[pos]) in keep: glyphs.append(data[pos:pos+size])
        pos += size
    assert {g[0] for g in glyphs} == {ord(c) for c in keep}
    header = data[:21]
    header[0] = len(glyphs)
    for index, lower in [(17,ord('A')), (19,ord('a'))]:
        offset = sum(len(g) for g in glyphs if g[0]<lower)
        header[index:index+2] = [offset>>8,offset&255]
    packed = header+[b for g in glyphs for b in g]+[0,0]
    # Independently traverse the encoded lookup table for every retained glyph.
    for glyph in glyphs:
        code = glyph[0]
        index = 19 if code >= ord('a') else (17 if code >= ord('A') else None)
        seek = 21 + (packed[index]*256 + packed[index+1] if index else 0)
        while packed[seek+1] and packed[seek] != code:
            seek += packed[seek+1]
        assert packed[seek:seek+len(glyph)] == glyph
    lines.append(f'const ucg_fntpgm_uint8_t {name}[{len(packed)}] UCG_FONT_SECTION("{name}") = {{')
    lines += ['  '+','.join(map(str,packed[i:i+20]))+',' for i in range(0,len(packed),20)]
    lines += ['};','']
    print(f'{original}: {len(data)} -> {len(packed)} bytes; {len(glyphs)} unchanged glyphs')
(root/'firmware/incubadora/display_font.h').write_text('\n'.join(lines))
